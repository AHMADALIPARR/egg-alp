#!/usr/bin/env bash
# Generate ALP facts for EGG-001 from egg/results/*.tsv, the raw CSV hash and the repo tree.
# Plain awk + coreutils only. All arithmetic/comparison (which ALP lacks) happens HERE and is
# emitted as explicit facts; the logic in egg/contracts/ only does unification and negation as failure.
# Usage: gen_facts.sh [REPO_ROOT] > facts/egg001_facts.alp
set -eu
R="${1:-$(cd "$(dirname "$0")/../../.." && pwd)}"
RES="$R/egg/results"
CSV="$R/data/basketdata-2000-04-01.csv"

echo "% GENERATED by egg/alp_check/gen_facts.sh from egg/results/*.tsv and the repo tree. Do not edit."
echo "% Constants are lowercased/sanitised: [a-z0-9_-]. Numbers are plain constants (ALP has no arithmetic)."

# ---- TSV-derived facts (single awk pass, dispatch on file name) ----
awk -F'\t' -v OFS='\t' '
function san(s) { s = tolower(s); gsub(/[^a-z0-9_-]/, "_", s); return s }
function fact(s) { print s "." }
FNR == 1 { f = FILENAME; sub(/.*\//, "", f); sub(/\.tsv$/, "", f); delete col; for (i = 1; i <= NF; i++) col[$i] = i; if (f != "awk_hist" ) next; }
f == "awk_integrity" {
  k = san($1); v = san($2); s = tolower($3)
  fact("check_status(" k "," s ")"); fact("check_value(" k "," v ")")
  if (s == "fail") nfail++
  val[k] = $2
  next
}
f == "awk_device" {
  if (!(rows_init)) { rows = val["meta_seconds_of_data"] + 0; t0 = val["meta_start_epoch"] + 0; t1 = val["meta_end_epoch"] + 0; rows_init = 1 }
  d = $1; npos++; dev[d] = 1
  nv = $2 + 0; nm = $3 + 0; runs = $8 + 0; lng = $9 + 0
  nvalid[d] = nv; nmiss[d] = nm
  fact("device_observed(" d ")"); fact("device_order(" npos "," d ")")
  fact("dev_n_valid(" d "," $2 ")"); fact("dev_n_missing(" d "," $3 ")")
  fact("dev_min(" d "," $6 ")"); fact("dev_max(" d "," $7 ")")
  fact("dev_missing_runs(" d "," $8 ")"); fact("dev_longest_missing_run(" d "," $9 ")")
  fact("dev_first_valid(" d "," $11 ")"); fact("dev_last_valid(" d "," $12 ")")
  # precomputed relations (ALP has no + or <=)
  if (nv + nm == rows) fact("dev_rows_balance(" d ")")
  if (nv > 0) fact("dev_n_positive(" d ")")
  if (((nm == 0) == (runs == 0)) && lng <= nm && (nm == 0 || lng >= 1)) fact("dev_missing_run_consistent(" d ")")
  for (c = 11; c <= 12; c++) { t = $c + 0; if ($c != "" && t >= t0 && t <= t1 && !(t in seen)) { seen[t] = 1; fact("within_utc_day(" $c ")") } }
  next
}
f == "awk_hist" {
  if (FNR == 1) { next }
  d = $1; tot = 0; for (i = 2; i <= NF; i++) tot += $i
  fact("hist_support(" d "," (NF - 1) ")"); fact("hist_total(" d "," tot ")"); fact("hist_bin0(" d "," $2 ")")
  if (nmiss[d] > 0 && $2 + 0 >= nmiss[d]) { fact("zero_imputation_signature(" d ")"); nzs++ }
  next
}
f == "awk_rowvalid" { fact("rowvalid(" $1 "," $2 ")"); rvsum += $2; rvn++; next }
f == "r_device_summary" {
  d = $col["device"]; hb = log(201) / log(2)
  fact("r_n_valid(" d "," $col["n_valid"] ")")
  hp = $col["H_plugin"] + 0; hm = $col["H_miller_madow"] + 0; hn = $col["Hmin_plugin"] + 0
  if (hp >= 0 && hp <= hb && hm >= 0 && hm <= hb && hn >= 0) fact("entropy_bounds_ok(" d ")")
  if (hn <= hp) fact("hmin_le_h(" d ")")
  if ($col["pearson_df"] + 0 == $col["bins_pooled"] - 1) fact("pearson_df_ok(" d ")")
  nm_ = split("pearson_p_holm lr_p_holm p_mean_holm p_var_holm pearson_p_mc_holm lr_p_mc_holm", cols, " ")
  for (j = 1; j <= nm_; j++) { c = cols[j]; if ($col[c] + 0 < 0.05) { fact("holm_reject(t1_" c "," d ")"); nrej++ } }
  next
}
f == "r_pooled_gof" { fact("pooled_n(" $col["n"] ")"); next }
f == "r_network_z_summary" {
  m = $1; v = $2
  if (m == "min_valid_devices") fact("network_min_valid(" v ")")
  if (m == "n_BH_q_lt_0.05") fact("network_bh_hits(" v ")")
  if (m == "seconds_with_zero_devices") fact("network_zero_device_seconds(" v ")")
  if (m == "var_Z_ci_lo_blockboot") lo = v + 0
  if (m == "var_Z_ci_hi_blockboot") { hi = v + 0; if (lo <= 1 && 1 <= hi) fact("var_z_ci_contains_one") }
  next
}
f == "r_crossdev_global" { if ($col["p_perm"] + 0 > 0.05) fact("crossdev_nonsig(" san($col["statistic"]) ")"); next }
f == "parity" { np++; if ($col["status"] != "PASS") npf++; next }
END {
  fact("awk_integrity_fail_count(" nfail + 0 ")")
  fact("zero_imputation_signature_count(" nzs + 0 ")")
  fact("holm_reject_count(t1," nrej + 0 ")")
  if (rvn > 0 && rvsum == rows) fact("rowvalid_total_ok")
  fact("parity_total(" np + 0 ")"); fact("parity_fail_count(" npf + 0 ")"); if (np > 0) fact("parity_has_rows(yes)")
}' "$RES/awk_integrity.tsv" "$RES/awk_device.tsv" "$RES/awk_hist.tsv" "$RES/awk_rowvalid.tsv" \
  "$RES/r_device_summary.tsv" "$RES/r_pooled_gof.tsv" "$RES/r_network_z_summary.tsv" \
  "$RES/r_crossdev_global.tsv" "$RES/parity.tsv"

# ---- which result files exist and have data rows ----
for f in "$RES"/*.tsv; do
  [ "$(wc -l < "$f")" -gt 1 ] && echo "result_file($(basename "$f" .tsv | tr 'A-Z' 'a-z'))."
done

# ---- source provenance ----
echo "source_sha256($(sha256sum "$CSV" | cut -d' ' -f1))."
if [ -z "$(git -C "$R" status --porcelain -- data 2>/dev/null)" ]; then echo "source_tree_status(clean)."; else echo "source_tree_status(dirty)."; fi
echo "data_csv_count($(ls "$R"/data/*.csv | wc -l | tr -d ' '))."
echo "dataset(basket,historical_replay)."
echo "represented_as(basket,physical_observation)."

# ---- runtime inventory, tool artifacts, event-data files ----
for d in "$R"/egg/*/; do
  n=$(basename "$d")
  case "$n" in contracts|alp_check|out|results) continue;; esac
  echo "runtime_component($n)."
done
for t in ampl awk dafny elixir futhark lean octave r sas tsql; do
  n=$(find "$R/egg/$t" -type f ! -path '*/_build/*' ! -path '*/deps/*' ! -path '*/.lake/*' ! -name '*.o' ! -name '*.so' 2>/dev/null | wc -l | tr -d ' ')
  if [ "$n" -gt 0 ]; then echo "tool_artifact_present($t)."; else echo "tool_artifact_absent($t)."; fi
done
ne=0
while IFS= read -r p; do
  [ -z "$p" ] && continue
  ne=$((ne+1)); echo "event_data_file($(echo "${p#$R/}" | tr 'A-Z' 'a-z' | sed 's/[^a-z0-9_-]/_/g'))."
done < <(find "$R/data" "$R/egg" -type f \( -iname '*event*' -o -iname '*intention*' -o -iname '*dream*' \) ! -path '*/contracts/*' ! -path '*/alp_check/*' ! -path '*/.lake/*' ! -path '*/_build/*' ! -path '*/out/*' 2>/dev/null)
echo "event_record_count($ne)."

# ---- claims-policy text scan (line-level heuristic; see README) ----
NEG='(^|[^a-z])(no|not|never|nothing|without|nor|unrelated|neither)([^a-z]|$)|n.t |only a way'
scan() { # class regex
  ( cd "$R"; { ls README.md data/README.md docs/*.md 2>/dev/null; find egg/ampl egg/awk egg/dafny egg/elixir egg/futhark egg/lean egg/octave egg/r egg/sas egg/tsql egg/tests -type f ! -path '*/.lake/*' ! -path '*/_build/*' ! -path '*/deps/*' ! -name '*.o' ! -name '*.so' 2>/dev/null; } \
    | while IFS= read -r f; do grep -inE "$2" "$f" 2>/dev/null | while IFS= read -r line; do
        tok=$(echo "$f" | tr 'A-Z' 'a-z' | sed 's/[^a-z0-9_-]/_/g')
        if echo "$line" | grep -qiE "$NEG"; then echo "policy_hit($tok,$1,negated)."; else echo "policy_hit($tok,$1,asserted)."; fi
      done; done ) | sort -u
}
scan llm_or_agent_runtime 'openai|anthropic|\bllm\b|langchain|chatgpt|gpt-[0-9]|language model|token sampl|agent orchestrat'
scan consciousness_claim 'conscious'
scan simulation_claim 'simulated universe|universe[^.]*simulat|simulation (hypothesis|theory|detector)|we are living in a simulation'
